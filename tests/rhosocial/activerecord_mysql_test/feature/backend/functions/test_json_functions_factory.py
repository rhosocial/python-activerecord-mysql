class TestJsonSearch:
    """Verify json_search builds JSON_SEARCH calls for one/all mode and paths."""

    def test_one_mode(self, dialect):
        """One mode should emit 'one' as the second argument."""
        call = json_search(dialect, Column(dialect, "data"), "John")
        sql, params = call.to_sql()
        assert sql == "JSON_SEARCH(`data`, %s, %s)", f"unexpected SQL: {sql}"
        assert params == ("one", "John"), "mode and search string should be bound"

    def test_all_mode(self, dialect):
        """All mode should emit 'all' as the second argument."""
        call = json_search(dialect, Column(dialect, "data"), "John", search_all=True)
        sql, params = call.to_sql()
        assert sql == "JSON_SEARCH(`data`, %s, %s)", f"unexpected SQL: {sql}"
        assert params == ("all", "John"), "mode and search string should be bound"

    def test_with_path(self, dialect):
        """With a path, a NULL escape and the path should be appended."""
        call = json_search(dialect, Column(dialect, "data"), "John", path="$.users", search_all=True)
        sql, params = call.to_sql()
        assert sql == "JSON_SEARCH(`data`, %s, %s, %s, %s)", f"unexpected SQL: {sql}"
        assert params == ("all", "John", None, "$.users"), "escape and path should be bound"


