def dialect():
    """Return a MySQLDialect instance for function formatting."""
    return MySQLDialect(version=(8, 0, 0))


class TestConvertToExpression:
    """Verify _convert_to_expression literal/column conversion rules."""

    def test_base_expression_passthrough(self, dialect):
        """A BaseExpression should be returned unchanged."""
        column = Column(dialect, "data")
        result = _convert_to_expression(dialect, column)
        assert result is column, "existing expression should pass through unchanged"

    def test_string_becomes_column(self, dialect):
        """A plain string should be converted to a Column."""
        result = _convert_to_expression(dialect, "data")
        assert isinstance(result, Column), "string input should become a Column"

    def test_numeric_becomes_literal(self, dialect):
        """An integer should become a Literal when numeric literals are handled."""
        result = _convert_to_expression(dialect, 42)
        assert isinstance(result, Literal), "integer input should become a Literal"

    def test_float_becomes_literal(self, dialect):
        """A float should become a Literal when numeric literals are handled."""
        result = _convert_to_expression(dialect, 3.14)
        assert isinstance(result, Literal), "float input should become a Literal"

    def test_numeric_handling_disabled(self, dialect):
        """A numeric input should become a Column when numeric literals are disabled."""
        result = _convert_to_expression(dialect, 42, handle_numeric_literals=False)
        assert isinstance(result, Column), "numeric input should become a Column when disabled"


class TestJsonExtract:
    """Verify json_extract builds JSON_EXTRACT function calls."""

    def test_single_path(self, dialect):
        """A single path should be bound as a parameter."""
        call = json_extract(dialect, Column(dialect, "data"), "$.name")
        assert isinstance(call, FunctionCall), "json_extract should return a FunctionCall"
        sql, params = call.to_sql()
        assert sql == "JSON_EXTRACT(`data`, %s)", f"unexpected SQL: {sql}"
        assert params == ("$.name",), "path should be bound as parameter"

    def test_multiple_paths(self, dialect):
        """Multiple paths should each be bound as parameters."""
        call = json_extract(dialect, Column(dialect, "data"), "$.name", "$.age", "$.city")
        sql, params = call.to_sql()
        assert sql == "JSON_EXTRACT(`data`, %s, %s, %s)", f"unexpected SQL: {sql}"
        assert params == ("$.name", "$.age", "$.city"), "all paths should be bound"

    def test_literal_document(self, dialect):
        """A literal JSON document should be rendered as a bound parameter."""
        call = json_extract(dialect, 5, "$.a")
        sql, params = call.to_sql()
        assert sql == "JSON_EXTRACT(%s, %s)", f"unexpected SQL: {sql}"
        assert params == (5, "$.a"), "numeric document should be a bound literal"


